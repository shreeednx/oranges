"""The back end's own shaders: host/vk/shaders/*.comp compiled into the SPIR-V headers host/vk includes.

The headers are checked in, so a build needs no glslang; this makes them again from their sources, or checks them.

    python -m oranges.shaders            write host/vk/shaders/<name>_comp_spv.h for each .comp there
    python -m oranges.shaders --check    compare instead of writing (exit 1 on a mismatch)

Each header names the SHA-256 of what it was made from (the .comp and the headers in its include folders) and the
glslang version that made it. --check always compares that hash, so a changed source with a stale header is found
without glslang; with glslang it also compiles and compares the SPIR-V words, unless the header was made by another
glslang version (equivalent SPIR-V may differ between versions: said as a note, not a failure).

Shaders: fsr1_easu, fsr1_rcas (FSR 1 at the present, on third_party/fidelityfx-fsr1).
"""
import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "host" / "vk" / "shaders"
FSR1 = ROOT / "third_party" / "fidelityfx-fsr1" / "include" / "FidelityFX" / "gpu"
# include folders per shader (by its name's prefix)
INCLUDES = {"fsr1_": [FSR1]}
TARGET = "vulkan1.3"


def includes(comp: Path) -> list[Path]:
    for prefix, dirs in INCLUDES.items():
        if comp.stem.startswith(prefix):
            return dirs
    return []


def source_hash(comp: Path) -> str:
    """SHA-256 over the shader's source and every header in its include folders (by relative path and content)"""
    h = hashlib.sha256(comp.read_bytes())
    for d in includes(comp):
        for f in sorted(p for p in d.rglob("*") if p.is_file()):
            h.update(b"\0" + str(f.relative_to(d)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()


def header_path(comp: Path) -> Path:
    return comp.with_name("%s_comp_spv.h" % comp.stem)


def glslang() -> str | None:
    return shutil.which("glslangValidator") or shutil.which("glslang")


def glslang_version(exe: str) -> str:
    out = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout
    m = re.search(r"Glslang Version: \S*?(\d+\.\d+\.\d+)", out)
    return m.group(1) if m else "unknown"


def compile_words(exe: str, comp: Path) -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / "out.spv"
        cmd = ([exe, "-V", "--target-env", TARGET] + ["-I" + str(d) for d in includes(comp)]
               + [str(comp), "-o", str(spv)])
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            raise SystemExit("%s: glslang failed:\n%s%s" % (comp.name, r.stdout, r.stderr))
        data = spv.read_bytes()
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def render(comp: Path, words: list[int], version: str) -> str:
    name = "%s_comp_spv" % comp.stem
    lines = ["// Generated by `python -m oranges.shaders` from %s: do not edit." % comp.name,
             "// source sha256 %s" % source_hash(comp),
             "// glslang %s, --target-env %s" % (version, TARGET),
             "#pragma once",
             "#include <cstdint>",
             "",
             "static const uint32_t %s[] = {" % name]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def parse(text: str) -> tuple[str | None, str | None, list[int]]:
    """(source hash, glslang version, words) of a header"""
    src = re.search(r"^// source sha256 ([0-9a-f]{64})$", text, re.M)
    ver = re.search(r"^// glslang (\S+),", text, re.M)
    body = text.split("[] = {", 1)[1] if "[] = {" in text else ""
    return (src.group(1) if src else None, ver.group(1) if ver else None,
            [int(w, 16) for w in re.findall(r"0x([0-9a-f]{8})", body)])


def run(check: bool, say=print) -> int:
    comps = sorted(SHADERS.glob("*.comp"))
    exe = glslang()
    if not exe and not check:
        raise SystemExit("glslang not found (glslangValidator)")
    version = glslang_version(exe) if exe else None
    bad = 0
    out = {}
    for comp in comps:
        hdr = header_path(comp)
        if check:
            if not hdr.exists():
                say("%s: missing" % hdr.name)
                bad += 1
                continue
            have_src, have_ver, have_words = parse(hdr.read_text())
            if have_src != source_hash(comp):
                say("%s: made from another source (run `python -m oranges.shaders`)" % hdr.name)
                bad += 1
                continue
            if exe:
                words = compile_words(exe, comp)
                if words != have_words:
                    if have_ver != version:
                        say("%s: note: glslang %s makes other SPIR-V than the header's %s (source unchanged)"
                            % (hdr.name, version, have_ver))
                    else:
                        say("%s: its SPIR-V differs from what its source compiles to" % hdr.name)
                        bad += 1
        else:
            out[hdr] = render(comp, compile_words(exe, comp), version)
    for hdr, text in out.items():   # (nothing written until every shader compiled)
        if not hdr.exists() or hdr.read_text() != text:
            hdr.write_text(text, newline="\n")
            say("wrote %s" % hdr.relative_to(ROOT))
    if check and not bad:
        say("%d shader headers match their sources" % len(comps))
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m oranges.shaders", description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare the headers instead of writing them")
    return run(ap.parse_args(argv).check)


if __name__ == "__main__":
    sys.exit(main())
